def test_github_actions_dispatch_and_ci_results(client):
    # 1. Dispatch CI
    dispatch_payload = {
        "project_id": "proj-core-payment-gateway",
        "branch": "agentic-qa/test-3ds2-payment",
        "inputs": {"environment": "staging", "headless": "true"}
    }
    dispatch_res = client.post("/api/v1/github/dispatch-ci", json=dispatch_payload, headers={"X-Demo-User-Role": "QA Engineer"})
    assert dispatch_res.status_code == 200
    dispatch_data = dispatch_res.json()
    assert bool(dispatch_data["run_id"])
    assert "gh-run-" in dispatch_data["run_id"]
    assert dispatch_data["dispatched"] is True


    # 2. Collect CI Results
    run_id = dispatch_data["run_id"]
    results_res = client.get(
        f"/api/v1/github/ci-results?project_id=proj-core-payment-gateway&run_id={run_id}",
        headers={"X-Demo-User-Role": "Viewer"}
    )
    assert results_res.status_code == 200
    results = results_res.json()
    assert results["total_tests"] > 0
    assert results["duration_seconds"] > 0
    assert "raw_logs" in results
    assert "artifacts_url" in results


def test_agent_6_failure_analyst_diagnostics():
    analyst = FailureAnalysisAgent()

    # Test 1: Selector Mutation
    diag_selector = analyst.analyze_failure(
        test_name="test_checkout_button_click",
        error_message="TimeoutError: locator.click: Timeout 10000ms exceeded waiting for locator('#checkout-submit-btn')",
        stack_trace="File 'pages/checkout_page.py', line 45, in submit_payment\n  self.submit_btn.click()"
    )
    assert diag_selector.root_cause_category == "locator_issue"
    assert diag_selector.confidence_score >= 0.85
    assert "locator" in diag_selector.explanation.lower() or "selector" in diag_selector.explanation.lower()
    assert len(diag_selector.suggested_fix) > 10

    # Test 2: Timing / Flakiness
    diag_timing = analyst.analyze_failure(
        test_name="test_async_order_processing",
        error_message="AssertionError: Expected order status 'PROCESSED' but got 'PENDING'",
        stack_trace="File 'tests/test_orders.py', line 88, in test_async_order\n  assert status == 'PROCESSED'"
    )
    assert diag_timing.root_cause_category == "flaky_test"
    assert diag_timing.confidence_score >= 0.80
    assert "retry" in diag_timing.suggested_fix.lower() or "wait" in diag_timing.suggested_fix.lower()

    # Test 3: Backend / App Defect
    diag_defect = analyst.analyze_failure(
        test_name="test_payment_api_response",
        error_message="HTTP 500 Internal Server Error in settlement microservice",
        stack_trace="File 'tests/test_api.py', line 112\n  assert res.status_code == 200"
    )
    assert diag_defect.root_cause_category == "application_defect"
    assert diag_defect.confidence_score >= 0.85

